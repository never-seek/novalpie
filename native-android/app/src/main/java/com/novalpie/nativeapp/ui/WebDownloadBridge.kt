  async function saveBlobOnce(anchor, href, fallbackFilename, fallbackMime) {
    inFlight.add(href);
    var key = null;
    var transfer = null;
    try {
      var blob = blobStore.get(href) || null;
      if (!blob) blob = await (await fetch(href)).blob();
      if (!blob) throw new Error('Blob download data missing');
      var mime = blob.type || fallbackMime || 'application/octet-stream';
      var filename = filenameFor(anchor, blob, fallbackFilename);
      key = downloadKeyFor(href, blob);
      // A completed Blob can later receive another object URL (for example after a page-side
      // retry UI rebuilds its invisible anchor). The native gate would prevent a second file,
      // but it would still have to drain an unnecessary second large upload. Completion must use
      // the Blob identity too, not only the object URL that happened to finish first.
      if (completedKeys.has(key)) {
        completed.add(href);
        blobStore.delete(href);
        return true;
